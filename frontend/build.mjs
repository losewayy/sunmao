import { build } from 'esbuild';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const assets = new URL('../crates/cli/src/serve/assets/', import.meta.url);
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/index.ts'],
  bundle: true,
  format: 'iife',
  globalName: 'SunmaoUI',
  platform: 'browser',
  target: ['chrome105', 'safari16.4'],
  // Escaped strings preserve dependency CSS without trailing whitespace in generated code.
  supported: { 'template-literal': false },
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '/* Generated by frontend/build.mjs. Source: frontend/src. Third-party licenses: ecosystem.licenses.txt. */' },
  footer: { js: 'window.SunmaoUI = SunmaoUI;' },
  write: false,
});

// Include complete runtime dependency licenses, not just the minifier's comments.
const lock = JSON.parse(await readFile(new URL('package-lock.json', import.meta.url), 'utf8'));
const notices = [];
for (const [path, info] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (!path || info.dev) continue;
  const dir = new URL(`${path}/`, import.meta.url);
  const files = (await readdir(dir)).filter(name => /^(license|licence|copying)(\.|$)/i.test(name)).sort();
  const name = JSON.parse(await readFile(new URL('package.json', dir), 'utf8')).name;
  const text = files.length
    ? (await Promise.all(files.map(name => readFile(new URL(name, dir), 'utf8')))).join('\n')
    : await readFile(new URL(`licenses/${name.replaceAll('/', '-')}.txt`, import.meta.url), 'utf8');
  notices.push(`${name} ${info.version}\n${text.replace(/\r\n/g, '\n').trim()}`);
}
const outputs = new Map([
  ['ecosystem.js', result.outputFiles[0].text],
  ['ecosystem.licenses.txt', notices.join('\n\n----------------------------------------\n\n') + '\n'],
]);
for (const [name, content] of outputs) {
  const path = new URL(name, assets);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`${name} is stale; run npm run build in frontend`);
  } else await writeFile(path, content);
}
console.log(`Frontend bundle ${Math.round(result.outputFiles[0].contents.length / 1024)} KiB; ${notices.length} runtime license entries; ${process.argv.includes('--check') ? 'verified' : 'built'}`);
